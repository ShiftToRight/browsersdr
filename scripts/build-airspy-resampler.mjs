// Optional reproducible generator; normal builds use checked-in standard-SIMD bytes.
// Usage: node scripts/build-airspy-resampler.mjs /path/to/wabt@1.0.37/index.js
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
if (!process.argv[2]) throw new Error("Supply wabt@1.0.37/index.js.");
const tool = pathToFileURL(process.argv[2]);
if (
  JSON.parse(await readFile(new URL("package.json", tool))).version !== "1.0.37"
)
  throw new Error("Use pinned wabt 1.0.37.");
const wabt = await (await import(tool.href)).default();
const source = await readFile(
  new URL("../wasm/airspy-resampler.wat", import.meta.url),
  "utf8",
);
const module = wabt.parseWat("airspy-resampler.wat", source, { simd: true });
module.validate({ simd: true, relaxed_simd: false });
const { buffer } = module.toBinary({
  canonicalize_lebs: true,
  write_debug_names: false,
});
if (!WebAssembly.validate(buffer))
  throw new Error("Host rejected Airspy resampler.");
const hash = (value) => createHash("sha256").update(value).digest("hex");
const rows = [];
for (let n = 0; n < buffer.length; n += 16)
  rows.push(`  ${Array.from(buffer.slice(n, n + 16)).join(", ")},`);
await writeFile(
  new URL("../src/radio/airspyResamplerBytes.ts", import.meta.url),
  `// Generated by scripts/build-airspy-resampler.mjs with wabt 1.0.37.\n// Source SHA-256: ${hash(source)}\n// Binary SHA-256: ${hash(buffer)}\nexport const AIRSPY_RESAMPLER = new Uint8Array([\n${rows.join("\n")}\n]);\n`,
);
console.log(
  JSON.stringify({
    sourceSha256: hash(source),
    binarySha256: hash(buffer),
    bytes: buffer.length,
  }),
);
module.destroy();
