export const bitCount = (value: number): number => {
  let n = 0;
  for (; value; value &= value - 1) n++;
  return n;
};
export function printable(value: string): string {
  return value.replaceAll("\r", "").replace(/[^\x20-\x7e£\n\t]/g, "");
}

